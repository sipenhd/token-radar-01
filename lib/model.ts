// Token Radar's valuation model, radar-2.
//
// One snapshot of the protocol universe in, one ranked board out. The board
// covers every slug in the snapshot's watchlist (the floor, never the
// ceiling) plus every other pre-token protocol the radar can rank: a
// protocol is pre-token when its record carries no token (no market cap, no
// CoinGecko id, no symbol), and rankable when it is not a wrapped, staked or
// bridged product of a token that already trades, not a centralised exchange
// and not a versioned pool -- the watchlist rule itself, applied to every
// row. Live-token protocols are kept apart and shown with the market's own
// values, never mixed into the ranked board.
//
// Implied value is a comparables valuation, computed from the snapshot
// itself at run time -- no protocol name is ever special-cased and no
// multiple is ever hand-written:
//
//   multiple   = median(market cap / TVL) of the live-token protocols in
//                the same category, when at least three of them report both
//                figures; otherwise the median across every live protocol
//                that reports both. Clamped to [0.05, 1.20] so one outlier
//                cannot set the price of a whole category.
//   growth     = clamp(change_7d, -50, 100) per cent
//   growthMult = 1 + (growth / 100) * 0.6
//   maturity   = 0.70 + min(age_days, 1095) / 1095 * 0.30
//                (age_days unknown: 365 -- the longer a protocol has run
//                with no token, the more value its launch has banked)
//   breadth    = 1 + 0.05 * min(chains - 1, 4)
//                (a protocol live on more chains reaches more farmers)
//   implied    = max(1, round(tvl_usd * multiple * growthMult
//                        * maturity * breadth))
//
// The medians come from the snapshot's own live set, so a new snapshot
// re-prices every row: the radar finds future launches early because it
// reads the market, not a list.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

